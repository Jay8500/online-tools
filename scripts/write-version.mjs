// Writes src/app/core/version.ts from package.json "version" + build date + git commit.
// Runs before `npm start` and `npm run build` (prestart / prebuild), so the site always shows the version it was built from.
// Release rule: new tool → minor (1.1.0), fix → patch (1.1.1), big redesign → major (2.0.0). Change it with:
//   npm version minor --no-git-tag-version
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const { version } = JSON.parse(readFileSync('package.json', 'utf8'));
let commit = (process.env.COMMIT_REF ?? '').slice(0, 7); // set by Netlify
if (!commit) {
  try {
    commit = execSync('git rev-parse --short HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  } catch {
    commit = 'local';
  }
}
// India date, e.g. "27 Oct 2026"
const built = new Date(Date.now() + 5.5 * 3600000).toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' });

writeFileSync(
  'src/app/core/version.ts',
  `// Generated by scripts/write-version.mjs — do not edit (change "version" in package.json instead).
export const APP_VERSION = { version: '${version}', built: '${built}', commit: '${commit}' } as const;
`,
);
console.log(`write-version: v${version} · ${built} · ${commit}`);
